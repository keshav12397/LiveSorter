// Round-trips EventPublisher -> LiveWireClient over a real loopback socket,
// with both halves in one process, and checks the three properties the fetch
// loop actually depends on:
//
//   1. Fidelity. Every record a reader receives is byte-identical to the one
//      published, and they arrive in order. This is what makes the shared
//      LiveWire.h header worth having; a packing or endian mistake shows up
//      here rather than as a raster full of nonsense.
//
//   2. publish() never blocks. Timed with the reader deliberately stalled,
//      so the socket's send buffer is full and the publisher thread is
//      parked in its WSAEWOULDBLOCK wait. If publish() were on the socket's
//      side of that, this is where the fetch loop would lose samples --
//      which is the whole reason EventPublisher is built the way it is.
//
//   3. Overflow drops the OLDEST and says so. A viewer that cannot keep up
//      must cost viewer data and nothing else, and the loss must be counted
//      rather than silent (same principle as StreamAccountant).
//
// Plus, for the version-2 protocol (LiveWire.h -- channel geometry preamble
// and kWireAmpChannel amplitude records for the live drift tracker):
//
//   4. The geometry preamble round-trips (per-unit channel count + x/y).
//   5. A version mismatch is refused loudly, not misparsed.
//   6. A preamble truncated mid-way through the new channel-count/geometry
//      arrays is refused loudly, not misparsed.
//   7. kWireAmpChannel records interleaved with kWireSpike records survive
//      the wire with every field routed correctly.
//   8. DriftTracker groups kWireAmpChannel records back into spikes by
//      (unit, sampleIndex) correctly even when channel records from two
//      different spikes arrive interleaved with each other.
//   9. DriftPool's pooledMedianMotion() matches
//      FilterGen/drift_estimate.pooled_com_motion()'s own pooling output on
//      a fixture generated by FilterGen/gen_drift_fixture.py -- see that
//      script's docstring for exactly what is and is not being checked.
//
// Build (from the repo root, with the MSVC env set -- see README):
//   cl.exe /EHsc /std:c++17 /Fe:TestLiveWireRoundtrip.exe ^
//       ClosedLoop\test_livewire_roundtrip.cpp ClosedLoop\EventPublisher.cpp ^
//       Viewer\LiveWireClient.cpp Viewer\DriftTracker.cpp Viewer\DriftPool.cpp ^
//       /I ClosedLoop /I Viewer
//
// Run with an optional fixture path (from
// `python FilterGen\gen_drift_fixture.py --out drift_fixture.bin`) to
// include test 9; without it, test 9 is skipped and said so, everything
// else still runs:
//   TestLiveWireRoundtrip.exe [drift_fixture.bin]

